/**
 * Embeds the SdFileExplorer file-type icon set into a TypeScript module.
 *
 * Source of truth: `versions/v19/projects/sdcorejs-angular/components/file-explorer/src/assets/icons`
 *   - `svg/*.svg`      one 64 × 64 icon per file
 *   - `manifest.json`  icon list, extension map and MIME fallbacks
 *
 * Output: `file-explorer-icons.generated.ts` next to the component. The icons ship inside the
 * library bundle, so consumers need no asset configuration. The v20/v21/v22 workspaces receive
 * the sources and the generated module through `npm run sync` like any other library file.
 *
 * Usage (repo root):
 *   node scripts/generate-file-explorer-icons.mjs          # write the module
 *   node scripts/generate-file-explorer-icons.mjs --check  # exit 1 when the module is stale
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const COMPONENT_DIR = join(REPO_ROOT, 'versions', 'v19', 'projects', 'sdcorejs-angular', 'components', 'file-explorer', 'src');
export const ICON_DIR = join(COMPONENT_DIR, 'assets', 'icons');
export const OUTPUT_FILE = join(COMPONENT_DIR, 'file-explorer-icons.generated.ts');

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

/**
 * Removes what only makes sense for a standalone file: the `<title>` (and its duplicated `id="title"`,
 * which would collide once several icons share a document), the ARIA wiring pointing at it and the fixed
 * width/height (the host sizes the icon). Whitespace between tags is collapsed.
 */
export function cleanSvg(svg) {
  return svg
    .replace(/<title\b[^>]*>[\s\S]*?<\/title>/g, '')
    .replace(/<svg\b([^>]*)>/, (_match, attributes) => `<svg${stripRootAttributes(attributes)}>`)
    .replace(/>\s+</g, '><')
    .trim();
}

function stripRootAttributes(attributes) {
  return attributes.replace(/\s(?:role|aria-labelledby|aria-label|width|height)="[^"]*"/g, '');
}

function key(name) {
  return IDENTIFIER.test(name) ? name : `'${name}'`;
}

function literal(value) {
  return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

function readIconSet(iconDir = ICON_DIR) {
  const manifest = JSON.parse(readFileSync(join(iconDir, 'manifest.json'), 'utf8'));
  const svgDir = join(iconDir, 'svg');
  const files = readdirSync(svgDir)
    .filter(file => file.endsWith('.svg'))
    .sort();
  const svgs = Object.fromEntries(files.map(file => [file.slice(0, -4), cleanSvg(readFileSync(join(svgDir, file), 'utf8'))]));
  return { manifest, svgs };
}

/** Validates the manifest against the SVG files; returns human-readable problems (empty when valid). */
export function validateIconSet({ manifest, svgs }) {
  const problems = [];
  const names = new Set(manifest.icons ?? []);
  for (const name of names) if (!svgs[name]) problems.push(`manifest icon "${name}" has no svg/${name}.svg`);
  for (const name of Object.keys(svgs)) if (!names.has(name)) problems.push(`svg/${name}.svg is not listed in manifest.icons`);
  const targets = [
    ['defaultIcon', manifest.defaultIcon],
    ['folder.closed', manifest.folder?.closed],
    ['folder.open', manifest.folder?.open],
    ...Object.entries(manifest.extensions ?? {}).map(([extension, icon]) => [`extensions.${extension}`, icon]),
    ...Object.entries(manifest.mimeFallback ?? {}).map(([mime, icon]) => [`mimeFallback.${mime}`, icon]),
  ];
  for (const [path, icon] of targets) if (!names.has(icon)) problems.push(`${path} points to unknown icon "${icon}"`);
  if (manifest.defaultIcon !== 'file-generic') problems.push('defaultIcon must stay "file-generic" (used as the resolver fallback)');
  if (manifest.folder?.closed !== 'folder-closed' || manifest.folder?.open !== 'folder-open') {
    problems.push('folder icons must stay "folder-closed" / "folder-open"');
  }
  return problems;
}

/** Builds the TypeScript module source (deterministic, Prettier-compatible). */
export function buildFileExplorerIconsModule(iconDir = ICON_DIR) {
  const iconSet = readIconSet(iconDir);
  const problems = validateIconSet(iconSet);
  if (problems.length) throw new Error(`Invalid SdFileExplorer icon set:\n- ${problems.join('\n- ')}`);
  const { manifest, svgs } = iconSet;
  const names = Object.keys(svgs).sort();
  const sortedEntries = record => Object.entries(record).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  const lines = [
    '// AUTO-GENERATED by scripts/generate-file-explorer-icons.mjs from ./assets/icons. DO NOT EDIT.',
    '// Run `npm run generate:file-explorer-icons` at the repo root after changing the SVG files or manifest.json.',
    '',
    '/** Name of a built-in SdFileExplorer file-type icon. */',
    'export type SdFileExplorerIconName =',
    ...names.map((name, index) => `  | ${literal(name)}${index === names.length - 1 ? ';' : ''}`),
    '',
    '/** Icon markup (64 × 64 viewBox), without title / ARIA / fixed size — rendered decoratively. */',
    'export const SD_FILE_EXPLORER_ICON_SVGS: Readonly<Record<SdFileExplorerIconName, string>> = {',
    // why: markup luôn dài hơn printWidth 140 — xuống dòng như Prettier để file sinh ra qua được lint.
    ...names.map(name => `  ${key(name)}:\n    ${literal(svgs[name])},`),
    '};',
    '',
    '/** Lower-case extension (including compound ones such as `tar.gz`) → icon. */',
    'export const SD_FILE_EXPLORER_ICON_EXTENSIONS: Readonly<Record<string, SdFileExplorerIconName>> = {',
    ...sortedEntries(manifest.extensions).map(([extension, icon]) => `  ${key(extension)}: ${literal(icon)},`),
    '};',
    '',
    '/** Exact MIME type, or a family prefix ending with `/`, → icon. Used when the extension is unknown. */',
    'export const SD_FILE_EXPLORER_ICON_MIME: Readonly<Record<string, SdFileExplorerIconName>> = {',
    ...sortedEntries(manifest.mimeFallback).map(([mime, icon]) => `  ${key(mime)}: ${literal(icon)},`),
    '};',
    '',
  ];
  return lines.join('\n');
}

function main() {
  const check = process.argv.includes('--check');
  const next = buildFileExplorerIconsModule();
  const current = existsSync(OUTPUT_FILE) ? readFileSync(OUTPUT_FILE, 'utf8').replace(/\r\n/g, '\n') : '';
  if (check) {
    if (current !== next) {
      console.error('[generate-file-explorer-icons] file-explorer-icons.generated.ts is stale. Run: npm run generate:file-explorer-icons');
      process.exit(1);
    }
    console.log('[generate-file-explorer-icons] up to date');
    return;
  }
  writeFileSync(OUTPUT_FILE, next);
  console.log(`[generate-file-explorer-icons] wrote ${OUTPUT_FILE}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
