function svgBlob(svg: string): Blob {
  return new Blob([svg], { type: 'image/svg+xml' });
}

function svgDataUrl(svg: string): string {
  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`;
}

/** One-page PDF generated in the browser so the demo needs no asset. */
function pdfBlob(title: string): Blob {
  const text = title.replace(/[()\\]/g, '');
  const stream = `BT /F1 26 Tf 72 740 Td (${text}) Tj ET BT /F1 13 Tf 72 700 Td (Generated by the sd-file-explorer demo.) Tj ET`;
  const pdf = [
    '%PDF-1.4',
    '1 0 obj <</Type /Catalog /Pages 2 0 R>> endobj',
    '2 0 obj <</Type /Pages /Kids [3 0 R] /Count 1>> endobj',
    '3 0 obj <</Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R /Resources <</Font <</F1 5 0 R>>>>>> endobj',
    `4 0 obj <</Length ${stream.length}>> stream`,
    stream,
    'endstream endobj',
    '5 0 obj <</Type /Font /Subtype /Type1 /BaseFont /Helvetica>> endobj',
    'trailer <</Root 1 0 R>>',
    '%%EOF',
  ].join('\n');
  return new Blob([pdf], { type: 'application/pdf' });
}

