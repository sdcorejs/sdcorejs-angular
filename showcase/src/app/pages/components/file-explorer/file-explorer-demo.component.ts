const DAY = 86_400_000;

/** Waits `ms`, rejecting with an `AbortError` as soon as `signal` aborts. */
function wait(ms: number, signal?: AbortSignal): Promise<void> {
  return new Promise((resolve, reject) => {
    const abort = () => reject(new DOMException('Aborted', 'AbortError'));
    if (signal?.aborted) return abort();
    const timer = setTimeout(resolve, ms);
    const onAbort = () => {
      clearTimeout(timer);
      abort();
    };
    signal?.addEventListener('abort', onAbort, { once: true });
  });
}

/** Reports progress in 50 steps over `durationMs`, like an XHR `progress` event would. */
async function simulateTransfer(
  total: number,
  durationMs: number,
  progress: (loaded: number, total?: number) => void,
  signal: AbortSignal
): Promise<void> {
  const steps = 50;
  for (let step = 1; step <= steps; step++) {
    await wait(durationMs / steps, signal);
    progress(Math.round((total * step) / steps), total);
  }
}

function normalize(value: string): string {
  return value
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/đ/g, 'd')
    .toLowerCase();
}

